#!/usr/bin/env python3
"""amp-build:2318 Free job-board XML feed (Indeed organic / Jooble / Talent.com style) -> /jobs-feed.xml.
Built ONLY from the same public JobPosting JSON-LD in tools/page-meta.json that each live /job/ page already
publishes (no client facility names, no invented cities/salaries). Called automatically at the end of
tools/build-pages.py; can also be run alone:  python3 tools/build-job-feed.py
Undo: delete jobs-feed.xml + this file and the 3-line hook at the bottom of build-pages.py (or git revert)."""
import datetime, json, os, subprocess
from xml.sax.saxutils import escape
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = "https://www.adaptivemedicalpartners.com"
meta = json.load(open(os.path.join(ROOT, "tools", "page-meta.json"), encoding="utf-8"))
STATES = {"AL":"Alabama","AK":"Alaska","AZ":"Arizona","AR":"Arkansas","CA":"California","CO":"Colorado","CT":"Connecticut",
"DE":"Delaware","FL":"Florida","GA":"Georgia","HI":"Hawaii","ID":"Idaho","IL":"Illinois","IN":"Indiana","IA":"Iowa","KS":"Kansas",
"KY":"Kentucky","LA":"Louisiana","ME":"Maine","MD":"Maryland","MA":"Massachusetts","MI":"Michigan","MN":"Minnesota","MS":"Mississippi",
"MO":"Missouri","MT":"Montana","NE":"Nebraska","NV":"Nevada","NH":"New Hampshire","NJ":"New Jersey","NM":"New Mexico","NY":"New York",
"NC":"North Carolina","ND":"North Dakota","OH":"Ohio","OK":"Oklahoma","OR":"Oregon","PA":"Pennsylvania","RI":"Rhode Island",
"SC":"South Carolina","SD":"South Dakota","TN":"Tennessee","TX":"Texas","UT":"Utah","VT":"Vermont","VA":"Virginia","WA":"Washington",
"WV":"West Virginia","WI":"Wisconsin","WY":"Wyoming","DC":"District of Columbia"}
def first_posted(path):
    f = os.path.join(ROOT, path.lstrip("/") + ".html")
    try:
        out = subprocess.run(["git", "-C", ROOT, "log", "--diff-filter=A", "--no-renames", "--format=%cs", "--", f],
                             capture_output=True, text=True, timeout=20).stdout.split()
        if out: return out[-1]
    except Exception: pass
    return datetime.date.today().isoformat()
def cdata(s): return "<![CDATA[" + (s or "").replace("]]>", "]]]]><![CDATA[>") + "]]>"
def build():
    rows = []
    for path, m in meta.items():
        if not path.startswith("/job/") or not m.get("jobld") or "noindex" in (m.get("robots") or ""): continue
        jo = json.loads(m["jobld"])
        addr = (jo.get("jobLocation") or {}).get("address") or {}
        posted = jo.get("datePosted") or first_posted(path)
        d = datetime.date.fromisoformat(posted[:10])
        desc = "<p>" + "</p><p>".join(escape(x.strip()) for x in (jo.get("description") or "").split("\n") if x.strip()) + "</p>"
        desc += '<p>Apply / talk with a recruiter: <a href="' + escape(jo.get("url") or SITE + path) + '">' + escape(jo.get("url") or SITE + path) + "</a></p>"
        ref = (jo.get("identifier") or {}).get("value") or path.rsplit("/", 1)[-1]
        rows.append((posted, "\n".join([
            "  <job>",
            "    <title>" + cdata(jo.get("title")) + "</title>",
            "    <date>" + cdata(d.strftime("%a, %d %b %Y") + " 00:00:00 CST") + "</date>",
            "    <referencenumber>" + cdata(ref) + "</referencenumber>",
            "    <url>" + cdata((jo.get("url") or SITE + path) + "?utm_source=jobfeed&utm_medium=organic") + "</url>",
            "    <company>" + cdata("Adaptive Medical Partners") + "</company>",
            "    <sourcename>" + cdata("Adaptive Medical Partners") + "</sourcename>",
            "    <city>" + cdata(addr.get("addressLocality", "")) + "</city>",
            "    <state>" + cdata(addr.get("addressRegion", "")) + "</state>",
            "    <statename>" + cdata(STATES.get(addr.get("addressRegion", ""), "")) + "</statename>",
            "    <country>" + cdata(addr.get("addressCountry", "US")) + "</country>",
            "    <postalcode>" + cdata(addr.get("postalCode", "")) + "</postalcode>",
            "    <category>" + cdata(jo.get("occupationalCategory", "")) + "</category>",
            "    <jobtype>" + cdata("fulltime" if jo.get("employmentType", "FULL_TIME") == "FULL_TIME" else jo.get("employmentType", "").lower()) + "</jobtype>",
            "    <description>" + cdata(desc) + "</description>",
            "  </job>"])))
    rows.sort(key=lambda r: r[0], reverse=True)
    now = datetime.datetime.now(datetime.timezone.utc).strftime("%a, %d %b %Y %H:%M:%S GMT")
    xml = ('<?xml version="1.0" encoding="utf-8"?>\n<!-- AMP public job feed: ' + str(len(rows)) +
           ' live jobs, generated by tools/build-job-feed.py from page-meta.json (same data as each job page JSON-LD). -->\n'
           "<source>\n  <publisher>Adaptive Medical Partners</publisher>\n  <publisherurl>" + SITE + "/</publisherurl>\n"
           "  <lastBuildDate>" + now + "</lastBuildDate>\n" + "\n".join(r[1] for r in rows) + "\n</source>\n")
    open(os.path.join(ROOT, "jobs-feed.xml"), "w", encoding="utf-8").write(xml)
    return len(rows)
if __name__ == "__main__":
    print("jobs-feed.xml:", build(), "jobs")
